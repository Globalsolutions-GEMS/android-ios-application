final Map<int, MobileMenuItem> menuById = {
  for (final item in mobileMenuItems) item.menuUniqueId: item,
};

/// Map for fast lookup by module
final Map<String, List<MobileMenuItem>> menuByModule = {
  for (final item in mobileMenuItems)
    item.module: [...(menuByModule[item.module] ?? []), item],
};
// Get menuUniqueId by module + title
int menuIdOf(String module, String title) =>
    mobileMenuItems
        .firstWhere((m) => m.module == module && m.title == title)
        .menuUniqueId;
